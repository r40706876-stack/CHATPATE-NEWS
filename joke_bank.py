def as_text(templates=TEMPLATES):
    out = []
    for i, t in enumerate(templates, 1):
        out.append(f"{i}. {t['name']} — {t['how']}\n   सबूत: {t['proof']}\n"
                   f"   उदाहरण → बबलू: \"{t['q']}\"\n             {t['who']}: \"{t['a']}\"")
    return "\n".join(out)


