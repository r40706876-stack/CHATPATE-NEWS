FRAG = re.compile(r"^\s*(जब|जितना|जितनी|क्योंकि|जिससे|जिसकी|जिसका|कि|और तभी|वरना)(?=[\s,…।]|$)")


_EXT = None


def _ext_sentences():
    """दूसरों की (Prakash Bharati वगैरह) असली lines — हमारी script में हूबहू/लगभग हूबहू नहीं आनी चाहिए."""
    global _EXT
    if _EXT is None:
        _EXT = []
        from pathlib import Path
        for f in ("yt_examples.json", "yt_examples_more.json"):
            fp = Path(__file__).parent / f
            if fp.exists():
                for v in json.load(open(fp, encoding="utf-8")):
                    _EXT += [x.strip() for x in re.split(r"[।?!.]", v.get("text", "")) if len(x.split()) >= 4]
    return _EXT


def copied_ext(lines):
    import difflib
    ext = _ext_sentences()
    bad = []
    for i, l in enumerate(lines):
        say = str(l.get("say", ""))
        for x in ext:
            if difflib.SequenceMatcher(None, say, x).ratio() > 0.72:
                bad.append(i)
                break
    return bad


def _code_check(c):
    """Gemini-जज के ऊपर पक्की जाँच: दूसरे का वाक्य पूरा करती अधूरी line = अंत फ़ेल (मालिक की 28 Oct शिकायत)."""
    lines = c["ep"].get("lines") or []
    cp = copied_ext(lines)
    c["ep"]["ref_lines"] = [lines[i].get("say", "") for i in cp]
    cp = cp[1:]                                             # मालिक (29 Oct): reference की 1 line चल सकती है (खबर में फ़िट हो); ज़्यादा = दोबारा
    if cp:
        v = c.setdefault("vote", {})
        v.setdefault("jaanch", {})["hasi"] = {"ok": False, "kyon": f"line {cp[0] + 1} दूसरे creator की line जैसी"}
        v["kamzor"] = sorted(set((v.get("kamzor") or []) + cp))
    bad = [i for i, l in enumerate(lines) if FRAG.search(str(l.get("say", "")))]
    if bad:
        v = c.setdefault("vote", {})
        j = v.setdefault("jaanch", {})
        j["ant"] = {"ok": False, "kyon": f"line {bad[0] + 1} अधूरा वाक्य (दूसरे की बात पूरी कर रही)"}
        v["kamzor"] = sorted(set((v.get("kamzor") or []) + bad))


def _fails(vote):
    j = (vote or {}).get("jaanch") or {}
    return [k for k, _ in QUESTIONS if not (j.get(k) or {}).get("ok")]


def _rank(vote):
    """पहले core सवाल पास, फिर कुल पास, फिर score."""
    f = _fails(vote)
    return (sum(k in CORE for k in f) == 0, len(QUESTIONS) - len(f), float((vote or {}).get("score", 0) or 0))


def prompt_punchup(items):
    return f"""तुम "बकरा न्यूज़" के punch-up writer हो. नीचे की scripts में दर्शक ने कुछ lines कमज़ोर बताईं (वजह साथ है)
और "fail" में वो सवाल हैं जिनका जवाब script नहीं देती:
{QTEXT}
अगर "ant" fail है: पहले आख़िरी 2 lines के 3 अलग अंत मन में लिखो, फिर सबसे तीखा-साफ़ चुनो.
कमज़ोर lines दोबारा लिखो और fail सवालों का जवाब script में डालो (ज़रूरत हो तो 1 line जोड़ सकते हो; कुल 5 से 8 lines —
5 से कम कभी नहीं) —
तथ्य, किरदार वही; बाकी अच्छी lines जस की तस. हर नई line पिछली से ज़्यादा
ठोस, ज़्यादा अनपेक्षित, और सीढ़ी में सही जगह. loop और आख़िरी वार न टूटे.
{json.dumps(items, ensure_ascii=False, indent=1)}

{PSYCH}

सिर्फ़ JSON: [{{"id": 0, "lines": [पूरी lines की नई list, हर line में वही सारे fields]}}]"""


def write(packs, n, fields, casting):
    """packs = gather() के तथ्य. लौटाता है episodes की list (lines वाले dicts), सबसे ऊँचे दर्शक-नंबर पहले."""
    prem = _ask(prompt_premises(packs), 1.0)
    chosen = []
    for t in prem if isinstance(prem, list) else []:
        if not isinstance(t, dict) or t.get("skip"):
            continue
        ps = sorted(t.get("premises") or [], key=lambda p: -(
            float(p.get("hasi", 0) or 0) + float(p.get("pehchaan_score", 0) or 0) + 1.5 * float(p.get("hook_score", 0) or 0)))
        if ps:
            pk = next((p for p in packs if str(p.get("topic", ""))[:20] in str(t.get("topic", "")) or
                       str(t.get("topic", ""))[:20] in str(p.get("topic", ""))), None)
            chosen.append({"topic": t.get("topic"), "facts": pk or {}, "premises": ps[:2]})
            print(f"  💡 {t.get('topic')}: {ps[0].get('premise', '')[:70]}")
    if not chosen:
        raise RuntimeError("एक भी premise नहीं बना")
    chosen = chosen[:n + 1]
    raw = _ask(prompt_scripts(chosen, fields, casting), 0.9, prefer="pro")   # लिखना = सबसे ताक़तवर model
    cands = []
    for t in raw if isinstance(raw, list) else []:
        for v in (t.get("versions") or [])[:2]:
            if isinstance(v, dict) and v.get("lines"):
                v["topic"] = t.get("topic")
                cands.append({"topic": t.get("topic"), "ep": v})
    if not cands:
        raise RuntimeError("script नहीं बनी")
    try:
        votes = _ask(prompt_audience(cands), 0.2)
        for vt in votes if isinstance(votes, list) else []:
            i = vt.get("id")
            if isinstance(i, int) and 0 <= i < len(cands):
                cands[i]["vote"] = vt
    except gemini.QuotaOver:
        raise
    except Exception as e:                                  # noqa: BLE001
        print("  दर्शक-जज नहीं चला:", repr(e)[:100])
    for c in cands:
        _code_check(c)

    def pick_best():
        best = {}
        for c in cands:                                     # हर खबर का A या B — 7 सवालों में जो ज़्यादा पास
            r = _rank(c.get("vote"))
            if c["topic"] not in best or r > best[c["topic"]][0]:
                best[c["topic"]] = (r, c)
        return [c for _, c in sorted(best.values(), key=lambda x: x[0], reverse=True)][:n]

    winners = pick_best()
    weak = [(k, c) for k, c in enumerate(winners) if _fails(c.get("vote")) or
            float((c.get("vote") or {}).get("score", 0) or 0) < 8]
    if weak:
        items = [{"id": k, "lines": c["ep"]["lines"], "kamzor": (c.get("vote") or {}).get("kamzor", []),
                  "fail": {q: ((c.get("vote") or {}).get("jaanch") or {}).get(q, {}).get("kyon", "")
                           for q in _fails(c.get("vote"))},
                  "darshak": [ln.get("kyon") for ln in (c.get("vote") or {}).get("lines", [])]} for k, c in weak]
        try:
            fixed = _ask(prompt_punchup(items), 0.9, prefer="pro")
            redo = []
            for f in fixed if isinstance(fixed, list) else []:
                k = f.get("id")
                if isinstance(k, int) and 0 <= k < len(winners) and isinstance(f.get("lines"), list) and \
                        len(f["lines"]) >= 5:
                    old_c = winners[k]
                    new_ep = dict(old_c["ep"], lines=f["lines"])
                    redo.append((k, {"topic": old_c["topic"], "ep": new_ep, "punched": True}))
            if redo:                                        # सुधरी script दोबारा उसी दर्शक को — बेहतर हो तभी बदलो
                votes = _ask(prompt_audience([c for _, c in redo]), 0.2)
                for (k, c), vt in zip(redo, votes if isinstance(votes, list) else []):
                    c["vote"] = vt
                    _code_check(c)
                    vt = c["vote"]
                    if _rank(vt) > _rank(winners[k].get("vote")):
                        winners[k] = c
                        print(f"  🥊 punch-up जीता: {c['topic']} (फ़ेल अब: {_fails(vt) or 'कोई नहीं'})")
        except gemini.QuotaOver:
            raise
        except Exception as e:                              # noqa: BLE001
            print("  punch-up नहीं हुआ:", repr(e)[:100])
    out = []
    for c in winners:
        ep, v = c["ep"], c.get("vote") or {}
        fails = _fails(v)
        ep["jaanch"] = {k: (v.get("jaanch") or {}).get(k) or {"ok": False, "kyon": "जज ने नहीं बताया"} for k, _ in QUESTIONS}
        ep["connect"] = {"score": v.get("score", "?"), "why": f"{len(QUESTIONS)} में से {len(QUESTIONS) - len(fails)} सवाल पास", "weak": "", "fix": ""}
        if any(k in CORE for k in fails):
            ep["_loose"] = True                             # Telegram पर ⚠️ और सबसे नीचे
        ep["writer"] = "psych" + ("+punchup" if c.get("punched") else "")
        out.append(ep)
        print(f"  👀 {c['topic']}: {v.get('score', '?')}/10, फ़ेल: {fails or 'कोई नहीं'}")
    out.sort(key=lambda e: bool(e.get("_loose")))
    return out
